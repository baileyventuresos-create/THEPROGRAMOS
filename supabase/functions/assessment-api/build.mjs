// THE PROGRAM OS — Bundle the assessment workflow for the Edge Function
// supabase/functions/assessment-api/build.mjs
//
// Generates vendor/workflow.bundle.mjs from the tested Node modules so
// the Deno Edge Function can import them. Run from this directory:
//
//   node build.mjs
//
// Uses the esbuild CLI via npx (downloaded on first run; no dependency
// is committed to the repo). Output is a build artifact: it is NOT
// committed to the repo. The function is not deployable until this has
// run and the bundle has been verified (see README.md §5).
//
// What gets bundled (the workflow's whole computation path):
//   server/assessment-workflow.js (the workflow factory)
//   server/assessment-access.js   (createAccessDirectory)
//   server/assessment-store.js    (recordAssessmentSession — the engine
//                                  path; the bundle's store argument is
//                                  supplied at runtime by store.ts, so the
//                                  Node MemoryAssessmentStore inside the
//                                  bundle is never used by the function)
//   server/assessment-battery.js, server/reassessment.js,
//   server/baseline-gating.js, server/progress.js,
//   server/smart-draft-adapter.js, assessment-engine/assessment-engine.js
//
// Deliberately NOT bundled: server/assessment-api.js (api.ts is the
// TypeScript port — the bundle only needs the workflow factory and
// the access directory), server/postgres-store.js (needs `pg`),
// server/reservation-stores.js (needs node:sqlite), server/api.js
// (reservation API — different function, if one is ever built).
// The bundle must stay free of Node built-ins; if esbuild reports a
// node:* import, stop — that is a design gap to report, not something
// to polyfill silently.

import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));

execFileSync(
  "npx",
  [
    "-y", "esbuild",
    path.join(here, "entry.mjs"),
    "--bundle",
    "--format=esm",
    "--platform=neutral",
    `--outfile=${path.join(here, "vendor", "workflow.bundle.mjs")}`,
    "--banner:js=// Generated by build.mjs — do not edit. Source: server/assessment-workflow.js + server/assessment-access.js + deps.",
    "--log-level=info",
  ],
  { stdio: "inherit" },
);

console.log("Bundle written to vendor/workflow.bundle.mjs (generated artifact — not committed).");
